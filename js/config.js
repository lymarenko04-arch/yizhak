const normC = s => String(s || '').toLowerCase().replace(/['`ʼ‘]/g, '’').replace(/^(м\.|місто)\s*/, '').replace(/\s+/g, ' ').trim();
// Пошук: спершу ті, що починаються з введеного, потім ті, що його містять.
export function findCities(q, max = 6) {
  const n = normC(q); if (!n) return [];
  const all = ALL_CITIES();
  return [...all.filter(c => normC(c).startsWith(n)), ...all.filter(c => !normC(c).startsWith(n) && normC(c).includes(n))].slice(0, max);
}
// Назва як у списку, якщо збігається; інакше як написала людина, з великої літери.
export function canonCity(v) {
  const n = normC(v); if (!n) return '';
  const hit = ALL_CITIES().find(c => normC(c) === n || normC(c).split(' (')[0] === n);
  if (hit) return hit;
  const t = String(v).replace(/^(м\.|місто)\s*/i, '').replace(/\s+/g, ' ').trim().slice(0, 40);
  return t.charAt(0).toUpperCase() + t.slice(1);
}

